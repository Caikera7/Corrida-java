package academy.devnunes.marratonajava.introducao;

public class EstruturaCondicionais2{
    
    public static void main(String[] args) {
     
        //ternary operator
        double salaryMen = 3000;
        String mensage = salaryMen > 3000 ? "Eu vou realizar o pagamento" : "Não vou realizar o pagamento";
        System.out.println(mensage);
        // (condição) ? verdadeiro : falso
    }
}
